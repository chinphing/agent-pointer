#!/usr/bin/env node
/**
 * Interactive setup for signing/macos/signing.env
 */
import fs from 'node:fs';
import readline from 'node:readline';
import {
  REPO_ROOT,
  SIGNING_ENV_PATH,
  SIGNING_ENV_EXAMPLE,
  parseEnvFile,
} from './lib/load-signing-env.mjs';

function ask(rl, question, defaultValue = '') {
  const hint = defaultValue ? ` [${defaultValue}]` : '';
  return new Promise((resolve) => {
    rl.question(`${question}${hint}: `, (answer) => {
      resolve(answer.trim() || defaultValue);
    });
  });
}

function askSecret(rl, question) {
  return new Promise((resolve) => {
    process.stdout.write(`${question}: `);
    const stdin = process.stdin;
    const wasRaw = stdin.isRaw;
    if (stdin.isTTY) stdin.setRawMode(true);
    stdin.resume();
    stdin.setEncoding('utf8');

    let value = '';
    const onData = (char) => {
      if (char === '\u0003') {
        process.stdout.write('\n');
        process.exit(130);
      }
      if (char === '\r' || char === '\n') {
        if (stdin.isTTY) stdin.setRawMode(wasRaw);
        stdin.removeListener('data', onData);
        process.stdout.write('\n');
        resolve(value);
        return;
      }
      if (char === '\u007f' || char === '\b') {
        value = value.slice(0, -1);
        return;
      }
      value += char;
    };
    stdin.on('data', onData);
  });
}

function loadDefaults() {
  if (fs.existsSync(SIGNING_ENV_PATH)) {
    return parseEnvFile(fs.readFileSync(SIGNING_ENV_PATH, 'utf8'));
  }
  if (fs.existsSync(SIGNING_ENV_EXAMPLE)) {
    return parseEnvFile(fs.readFileSync(SIGNING_ENV_EXAMPLE, 'utf8'));
  }
  return {};
}

function writeSigningEnv(values) {
  const lines = [
    '# Generated by npm run signing:macos:setup — do not commit (gitignored)',
    '',
    `# Certificate (.p12)`,
    `APPLE_CERTIFICATE_PATH=${values.APPLE_CERTIFICATE_PATH}`,
    `APPLE_CERTIFICATE_PASSWORD=${values.APPLE_CERTIFICATE_PASSWORD}`,
    '',
    `APPLE_SIGNING_IDENTITY=${values.APPLE_SIGNING_IDENTITY}`,
    `APPLE_TEAM_ID=${values.APPLE_TEAM_ID}`,
    '',
    `# Notarization (optional — only needed for npm run build:macos:signed)`,
    values.APPLE_ID ? `APPLE_ID=${values.APPLE_ID}` : '# APPLE_ID=',
    values.APPLE_PASSWORD ? `APPLE_PASSWORD=${values.APPLE_PASSWORD}` : '# APPLE_PASSWORD=',
    '',
    `# Optional: App Store Connect API (leave empty to use Apple ID above)`,
    `# APPLE_API_ISSUER=`,
    `# APPLE_API_KEY=`,
    `# APPLE_API_KEY_PATH=signing/macos/AuthKey_XXXXXXXXXX.p8`,
    '',
    `MACOS_BUILD_ARCH=${values.MACOS_BUILD_ARCH || 'universal'}`,
    '',
  ];
  fs.mkdirSync(`${REPO_ROOT}/signing/macos`, { recursive: true });
  fs.writeFileSync(SIGNING_ENV_PATH, lines.join('\n'), { mode: 0o600 });
}

async function main() {
  if (process.platform !== 'darwin') {
    console.error('macOS signing setup must run on macOS.');
    process.exit(1);
  }

  const defaults = loadDefaults();
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });

  console.log('\nPointer macOS signing setup');
  console.log('Fill in your Apple Developer credentials. Input is hidden for passwords.\n');
  console.log('Tip: after importing p12, run: security find-identity -v -p codesigning\n');

  const values = {};
  values.APPLE_CERTIFICATE_PATH = await ask(
    rl,
    'Path to .p12 certificate',
    defaults.APPLE_CERTIFICATE_PATH || 'path/to/DeveloperID.p12',
  );
  values.APPLE_CERTIFICATE_PASSWORD = await askSecret(rl, 'p12 export password');
  values.APPLE_SIGNING_IDENTITY = await ask(
    rl,
    'Signing identity (Developer ID Application: ...)',
    defaults.APPLE_SIGNING_IDENTITY || '',
  );
  values.APPLE_TEAM_ID = await ask(
    rl,
    'Apple Team ID (10 chars, optional for sign-only)',
    defaults.APPLE_TEAM_ID || '',
  );

  const notarizeAnswer = await ask(
    rl,
    'Configure notarization? (y/n)',
    defaults.APPLE_ID ? 'y' : 'n',
  );
  const configureNotarization = /^y(es)?$/i.test(notarizeAnswer);

  if (configureNotarization) {
    values.APPLE_ID = await ask(rl, 'Apple ID email', defaults.APPLE_ID || '');
    values.APPLE_PASSWORD = await askSecret(
      rl,
      'App-specific password (not Apple ID login password)',
    );
  } else {
    values.APPLE_ID = '';
    values.APPLE_PASSWORD = '';
    console.log('\nSkipping notarization — use npm run build:macos:sign-only');
  }

  values.MACOS_BUILD_ARCH = await ask(
    rl,
    'Build arch (universal | native)',
    defaults.MACOS_BUILD_ARCH || 'universal',
  );

  rl.close();
  writeSigningEnv(values);

  console.log(`\nSaved ${SIGNING_ENV_PATH}`);
  console.log('Next:');
  console.log('  npm run build:macos:sign-only   # sign only');
  if (configureNotarization) {
    console.log('  npm run build:macos:signed      # sign + notarize');
  }
  console.log('');
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
