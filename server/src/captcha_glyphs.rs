//! Built-in single-stroke glyph table for the SVG captcha.
//!
//! The captcha used to render each character as `<text>`, which meant the
//! answer was readable straight out of the SVG source (`<text>Y</text>` …) —
//! no OCR needed. Characters are now drawn as vector polylines from this
//! table, so the response carries geometry only: no character, no font
//! dependency, nothing to regex out.
//!
//! Coordinates are on a 6 × 10 grid with `y` pointing **down** (SVG space).
//! Each entry is a list of strokes; a stroke is a list of points drawn as a
//! single polyline.

/// Glyph box width in grid units.
pub const GLYPH_W: f32 = 6.0;
/// Glyph box height in grid units.
pub const GLYPH_H: f32 = 10.0;

type Stroke = &'static [(f32, f32)];
type Glyph = &'static [Stroke];

/// Strokes for `ch`, or `None` when the character has no glyph.
pub fn glyph_strokes(ch: char) -> Option<Glyph> {
    let upper = ch.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(glyph, _)| *glyph == upper)
        .map(|(_, strokes)| *strokes)
}

