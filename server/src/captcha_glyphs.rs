#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_captcha_alphabet_char_has_a_glyph() {
        for byte in crate::captcha::captcha_alphabet() {
            let ch = *byte as char;
            assert!(
                glyph_strokes(ch).is_some(),
                "captcha alphabet contains `{ch}` but the stroke table has no glyph"
            );
        }
    }

    #[test]
    fn digits_and_letters_are_covered() {
        for ch in ('0'..='9').chain('A'..='Z') {
            assert!(glyph_strokes(ch).is_some(), "missing glyph for `{ch}`");
        }
        assert!(glyph_strokes('a').is_some(), "lowercase folds to uppercase");
        assert!(glyph_strokes('?').is_none(), "unknown chars have no glyph");
    }

    #[test]
    fn glyphs_stay_inside_the_grid() {
        for (ch, strokes) in GLYPHS {
            for stroke in *strokes {
                assert!(stroke.len() >= 2, "`{ch}` has a degenerate stroke");
                for (x, y) in *stroke {
                    assert!(
                        (0.0..=GLYPH_W).contains(x) && (0.0..=GLYPH_H).contains(y),
                        "`{ch}` stroke point ({x}, {y}) is outside the glyph box"
                    );
                }
            }
        }
    }
}
